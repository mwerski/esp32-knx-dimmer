#!/usr/bin/env python3
"""Generate the fixed DownLight / NightLight dimming curves for Yeelight YLDL01YL.

Both lights get the same dimming value (0..255), the curves split the range:
NightLight covers the low end, DownLight the high end, both are on in a short crossover.

Model:
- The perceived brightness (CIE 1976 L*) rises linearly with the dimming value,
  so every dimming step looks equally large. The total light output Y (relative
  luminance, 1.0 = DownLight at full power) follows the inverse CIE L* function.
- The light output of each LED is proportional to the PWM duty above a threshold
  (PWM value where the LED starts to glow, e.g. caused by the LED driver).
- The NightLight reaches its full output at the split index, so its maximum flux
  relative to the DownLight is Y(SPLIT).
- In the crossover window the total output is shared with a smoothstep weight,
  so the sum of both lights still follows the curve (no jump, no dip).

Usage: python3 tools/gen_yldl01yl_curves.py  (writes src/yldl01yl_curves.h)
"""

import os

# ---- parameters ----
SPLIT = 75              # dimming value where the NightLight hands over to the DownLight (75 = ~29%)
CROSSOVER = 10          # width of the crossover window (both lights on)
DOWN_PWM_THRESHOLD = 76  # PWM where the DownLight starts to glow (default lookupTable at 25%)
NIGHT_PWM_THRESHOLD = 0  # PWM where the NightLight starts to glow
PWM_MAX = 1023
SIZE = 256


def cie_lightness_to_luminance(l_star):
    """Inverse CIE 1976 L* (0..100) -> relative luminance (0..1)."""
    if l_star <= 8.0:
        return l_star / 903.3
    return ((l_star + 16.0) / 116.0) ** 3


def smoothstep(x):
    return x * x * (3.0 - 2.0 * x)


def pwm(flux, threshold):
    """Relative flux of one LED (0..1) -> PWM value, 0 stays off."""
    if flux <= 0.0:
        return 0
    return min(PWM_MAX, round(threshold + flux * (PWM_MAX - threshold)))


def generate():
    total = [cie_lightness_to_luminance(100.0 * i / (SIZE - 1)) for i in range(SIZE)]
    start = SPLIT - CROSSOVER // 2
    end = start + CROSSOVER  # first index with DownLight only

    weights = []
    for i in range(SIZE):
        if i < start:
            weights.append(0.0)
        elif i >= end:
            weights.append(1.0)
        else:
            weights.append(smoothstep((i - start + 1) / (CROSSOVER + 1)))

    # NightLight runs at full power at its peak (start of the crossover)
    night_max = max(y * (1.0 - w) for y, w in zip(total, weights))

    down, night = [], []
    for y, w in zip(total, weights):
        down.append(pwm(y * w, DOWN_PWM_THRESHOLD))
        night.append(pwm(y * (1.0 - w) / night_max, NIGHT_PWM_THRESHOLD))

    assert len(down) == len(night) == SIZE
    assert down[0] == 0 and night[0] == 0 and down[-1] == PWM_MAX
    assert all(a <= b for a, b in zip(down, down[1:])), "DownLight curve not monotonic"
    return down, night, night_max, start, end


def fmt(values):
    rows = []
    for r in range(0, SIZE, 16):
        rows.append("  " + ", ".join(str(v) for v in values[r:r + 16]) + ("," if r < SIZE - 16 else ""))
    return "\n".join(rows)


def main():
    down, night, night_max, start, end = generate()
    header = f"""#pragma once
#include <stdint.h>

// Fixed dimming curves for Yeelight YLDL01YL (Meteorite)
// Generated by tools/gen_yldl01yl_curves.py, do not edit by hand.
//
// DownLight (CH2) and NightLight (CH3) are dimmed with the same value,
// the curves split the range: NightLight covers the low end, DownLight the high end.
// - perceived brightness (CIE L*) rises linearly with the dimming value
// - split at index {SPLIT}, crossover (both lights on) at index {start}..{end - 1}
// - DownLight PWM threshold {DOWN_PWM_THRESHOLD}, NightLight PWM threshold {NIGHT_PWM_THRESHOLD}
// - assumed NightLight max flux: {night_max * 100:.1f}% of the DownLight max flux
//
// Both tables must have exactly 256 entries (0..1023), see KnxLed::configDimCurve()

const uint16_t yldl01ylDownLightCurve[256] = {{
{fmt(down)}
}};

const uint16_t yldl01ylNightLightCurve[256] = {{
{fmt(night)}
}};
"""
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "yldl01yl_curves.h")
    with open(path, "w") as f:
        f.write(header)
    print(f"written {os.path.normpath(path)}")
    print("idx  down  night")
    for i in list(range(0, 12)) + list(range(start - 3, end + 3)) + [128, 192, 255]:
        print(f"{i:3d}  {down[i]:4d}  {night[i]:5d}")


if __name__ == "__main__":
    main()
